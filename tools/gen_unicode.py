"""Generate src/unicode_data.h: sorted codepoint ranges with flags (letter/number/whitespace).
Run: python tools/gen_unicode.py > src/unicode_data.h"""
import sys, unicodedata
WS = set([0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000]) | set(range(0x9, 0xE)) | set(range(0x2000, 0x200B))
def flag(c):
    if c in WS: return 4
    cat = unicodedata.category(chr(c))
    if cat[0] == 'L': return 1
    if cat[0] == 'N': return 2
    return 0
ranges = []
cur = None
for c in range(0x110000):
    f = flag(c)
    if cur and cur[2] == f and cur[1] == c - 1:
        cur[1] = c
    else:
        if cur and cur[2]: ranges.append(cur)
        cur = [c, c, f]
if cur and cur[2]: ranges.append(cur)
out = sys.stdout
out.write("/* generated by tools/gen_unicode.py from Python %s unicodedata %s - do not edit */\n" % (sys.version.split()[0], unicodedata.unidata_version))
out.write("#define UNI_LETTER 1\n#define UNI_NUMBER 2\n#define UNI_SPACE 4\n")
out.write("static const unsigned int uni_ranges[%d][3] = {\n" % len(ranges))
for i in range(0, len(ranges), 4):
    out.write("  " + " ".join("{0x%X,0x%X,%d}," % tuple(r) for r in ranges[i:i+4]) + "\n")
out.write("};\n")
