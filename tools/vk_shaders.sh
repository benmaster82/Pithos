#!/bin/sh
# Compile src/kernels_dx.hlsl and kernels_dx_token.hlsl into src/kernels_vk.h (SPIR-V for gpu_vulkan.c),
# as tools/vk_shaders.cmd does on Windows. Needs a dxc built with SPIR-V support (the release from
# github.com/microsoft/DirectXShaderCompiler, or the Vulkan SDK's): DXC=path/to/dxc, else dxc on PATH.
# The generated header is committed, so normal builds do not need it.
set -e
cd "$(dirname "$0")/.."
DXC=${DXC:-dxc}
command -v "$DXC" >/dev/null 2>&1 || { echo "[vk] dxc with SPIR-V support not found: set DXC"; exit 1; }
# the defines select Vulkan's aligned block layouts (Q8_BYTES etc. in gpu_vulkan.c)
OPT="-spirv -T cs_6_0 -O3 -fspv-target-env=vulkan1.1 -fvk-t-shift 8 0 -fvk-b-shift 16 0 -D PITHOS_VK -D Q8_BYTES=272 -D Q8_D=256 -D Q8_QS=0 -D Q6K_BYTES=224 -D Q6_D=208 -D Q6_QL=0 -D Q6_QH=128 -D Q6_SC=192"
OUT=src/kernels_vk.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
echo "/* kernels_vk.h - generated by tools\\vk_shaders.cmd from kernels_dx.hlsl and kernels_dx_token.hlsl: do not edit. */" > "$TMP/out.h"
for e in mm_q4_K mm_q6_K mv_q4_K mv_q6_K; do
    "$DXC" $OPT -E $e -Vn g_vk_$e -Fh "$TMP/$e.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
# the matmul kernels again for Intel GPUs (see kernels_dx.hlsl)
for e in mm_q4_K mm_q6_K mv_q4_K mv_q6_K; do
    "$DXC" $OPT -D MM_INTEL -D MV_LANES=8 -D MV_LOG2=3 -D MV_GROUP=128 -D MV_SWAR -E $e -Vn g_vk_${e}_intel -Fh "$TMP/$e.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
for e in resid_norm quant silu_quant shortconv attn_prep attention conv_chunk conv_state attn_chunk; do
    "$DXC" $OPT -E $e -Vn g_vk_$e -Fh "$TMP/$e.h" src/kernels_dx_token.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
mv "$TMP/out.h" "$OUT"
echo "[vk] ok: $OUT"
