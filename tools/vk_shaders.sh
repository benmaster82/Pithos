#!/bin/sh
# Compile src/kernels_dx.hlsl and kernels_dx_token.hlsl into src/kernels_vk.h (SPIR-V for gpu_vulkan.c),
# as tools/vk_shaders.cmd does on Windows. Needs a dxc built with SPIR-V support (the release from
# github.com/microsoft/DirectXShaderCompiler, or the Vulkan SDK's): DXC=path/to/dxc, else dxc on PATH.
# The generated header is committed, so normal builds do not need it.
set -e
cd "$(dirname "$0")/.."
DXC=${DXC:-dxc}
command -v "$DXC" >/dev/null 2>&1 || { echo "[vk] dxc with SPIR-V support not found: set DXC"; exit 1; }
# the defines select Vulkan's aligned block layouts (Q8_BYTES etc. in gpu_vulkan.c)
OPT="-spirv -T cs_6_0 -O3 -fspv-target-env=vulkan1.1 -fvk-t-shift 8 0 -fvk-b-shift 16 0 -D PITHOS_VK -D Q8_BYTES=272 -D Q8_D=256 -D Q8_QS=0 -D Q6K_BYTES=224 -D Q6_D=208 -D Q6_QL=0 -D Q6_QH=128 -D Q6_SC=192"
OUT=src/kernels_vk.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
echo "/* kernels_vk.h - generated by tools\\vk_shaders.cmd from kernels_dx.hlsl and kernels_dx_token.hlsl: do not edit. */" > "$TMP/out.h"
for e in mm_q4_K mm_q6_K mm_q8_0 mv_q4_K mv_q6_K mv_q8_0; do
    "$DXC" $OPT -E $e -Vn g_vk_$e -Fh "$TMP/$e.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
# the matrix-vector kernels again for the routed experts in VRAM (MV_EXPERTS in kernels_dx.hlsl)
for e in q4_K q6_K q8_0; do
    "$DXC" $OPT -D MV_EXPERTS -E mv_$e -Vn g_vk_mvx_$e -Fh "$TMP/mvx_$e.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/mvx_$e.h" >> "$TMP/out.h"
done
# NVFP4 (Inkling's experts in VRAM) on its own, so that the kernels above do not change
"$DXC" $OPT -D MV_EXPERTS -D MV_NVFP4 -E mv_nvfp4 -Vn g_vk_mvx_nvfp4 -Fh "$TMP/mvx_nvfp4.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
cat "$TMP/mvx_nvfp4.h" >> "$TMP/out.h"
# IQ2 / IQ3_XXS as nibbles (Inkling's smaller files), on its own as well
"$DXC" $OPT -D MV_EXPERTS -D MV_IQ -E mv_iq -Vn g_vk_mvx_iq -Fh "$TMP/mvx_iq.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
cat "$TMP/mvx_iq.h" >> "$TMP/out.h"
"$DXC" $OPT -D MV_EXPERTS -D MV_Q2 -E mv_q2_0 -Vn g_vk_mvx_q2_0 -Fh "$TMP/mvx_q2_0.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
cat "$TMP/mvx_q2_0.h" >> "$TMP/out.h"
# the matmul kernels again for Intel GPUs (see kernels_dx.hlsl)
for e in mm_q4_K mm_q6_K mm_q8_0 mv_q4_K mv_q6_K mv_q8_0; do
    "$DXC" $OPT -D MM_INTEL -D MV_LANES=8 -D MV_LOG2=3 -D MV_GROUP=128 -D MV_SWAR -E $e -Vn g_vk_${e}_intel -Fh "$TMP/$e.h" src/kernels_dx.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
for e in resid_norm quant silu_quant shortconv attn_prep attention conv_chunk conv_state attn_chunk moe_resid delta_conv delta_rec qattn_prep qattn router moe_combine ik_mix ik_norm ik_ctl ik_add ik_conv ik_prep ik_attn ik_situ; do
    "$DXC" $OPT -E $e -Vn g_vk_$e -Fh "$TMP/$e.h" src/kernels_dx_token.hlsl >/dev/null || { echo "[vk] shader compilation failed"; exit 1; }
    cat "$TMP/$e.h" >> "$TMP/out.h"
done
mv "$TMP/out.h" "$OUT"
echo "[vk] ok: $OUT"
